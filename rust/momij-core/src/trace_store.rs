//! Lightweight structured trace store: one JSON record per request, persisted
//! after the response (fire-and-forget). Ported from the compositor TraceStore
//! concept, kept minimal: write / list / get. Port of `TraceStore.swift`.

use std::fs;
use std::path::{Path, PathBuf};
use std::sync::Mutex;
use std::time::SystemTime;

use serde_json::Value;

use crate::json::random_id;

#[derive(Debug)]
pub struct TraceStore {
    dir: PathBuf,
    gate: Mutex<()>,
}

impl TraceStore {
    pub fn new(dir: impl Into<PathBuf>) -> Self {
        let dir = dir.into();
        let _ = fs::create_dir_all(&dir);
        Self {
            dir,
            gate: Mutex::new(()),
        }
    }

    pub fn new_id() -> String {
        random_id("tr-")
    }

    pub fn dir(&self) -> &Path {
        &self.dir
    }

    /// Atomically persist one trace record (fire-and-forget; failures are
    /// swallowed so tracing can never fail a request).
    pub fn write(&self, record: &Value, id: &str) {
        let _guard = self
            .gate
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        let Ok(data) = serde_json::to_vec_pretty(record) else {
            return;
        };
        let path = self.path_for(id);
        let tmp = path.with_extension("json.tmp");
        if fs::write(&tmp, data).is_err() {
            return;
        }
        if fs::rename(&tmp, &path).is_err() {
            let _ = fs::remove_file(&tmp);
        }
    }

    /// Newest records by modification time, up to `limit` (clamped to 1...200).
    pub fn list(&self, limit: usize) -> Vec<Value> {
        let _guard = self
            .gate
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        let Ok(entries) = fs::read_dir(&self.dir) else {
            return Vec::new();
        };
        let mut files: Vec<(SystemTime, PathBuf)> = entries
            .filter_map(Result::ok)
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|x| x == "json"))
            .map(|p| {
                (
                    fs::metadata(&p)
                        .and_then(|m| m.modified())
                        .unwrap_or(SystemTime::UNIX_EPOCH),
                    p,
                )
            })
            .collect();
        files.sort_by_key(|f| std::cmp::Reverse(f.0));
        files
            .into_iter()
            .take(limit.clamp(1, 200))
            .filter_map(|(_, p)| read_object(&p))
            .collect()
    }

    pub fn get(&self, id: &str) -> Option<Value> {
        let _guard = self
            .gate
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        read_object(&self.path_for(id))
    }

    /// Record ids are generated by [`TraceStore::new_id`], but `get` receives
    /// ids from URLs: keep the lookup inside the store directory.
    fn path_for(&self, id: &str) -> PathBuf {
        let safe: String = id
            .chars()
            .filter(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_'))
            .collect();
        self.dir.join(format!("{safe}.json"))
    }
}

fn read_object(path: &Path) -> Option<Value> {
    let data = fs::read(path).ok()?;
    match serde_json::from_slice::<Value>(&data) {
        Ok(v @ Value::Object(_)) => Some(v),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use std::thread::sleep;
    use std::time::Duration;

    use serde_json::json;

    use super::*;

    fn store() -> (tempfile::TempDir, TraceStore) {
        let tmp = tempfile::tempdir().unwrap();
        let store = TraceStore::new(tmp.path().join("traces"));
        (tmp, store)
    }

    #[test]
    fn write_list_get_roundtrip() {
        let (_tmp, store) = store();
        let id = TraceStore::new_id();
        assert!(id.starts_with("tr-"), "{id}");
        store.write(
            &json!({"ok": true, "locus": "none", "usage": {"prompt": 5}}),
            &id,
        );
        let got = store.get(&id).expect("record");
        assert_eq!(got["locus"], "none");
        let list = store.list(10);
        assert_eq!(list.len(), 1);
        assert!(
            list[0].get("id").is_none(),
            "id is the filename, not duplicated"
        );
    }

    #[test]
    fn list_newest_first() {
        let (_tmp, store) = store();
        for n in 0..5 {
            store.write(&json!({"ok": true, "n": n}), &TraceStore::new_id());
            sleep(Duration::from_millis(20));
        }
        let list = store.list(5);
        assert_eq!(list.len(), 5);
        assert_eq!(list[0]["n"], 4);
        assert_eq!(store.list(2).len(), 2);
    }

    #[test]
    fn get_unknown_returns_none() {
        let (_tmp, store) = store();
        assert!(store.get("tr-nonexistent").is_none());
    }

    #[test]
    fn get_cannot_escape_the_store_directory() {
        let (tmp, store) = store();
        fs::write(tmp.path().join("secret.json"), r#"{"k": 1}"#).unwrap();
        assert!(store.get("../secret").is_none());
        assert!(store.get("..%2Fsecret").is_none());
    }

    #[test]
    fn non_object_and_non_json_files_are_skipped() {
        let (_tmp, store) = store();
        fs::write(store.dir().join("a.json"), "[1,2]").unwrap();
        fs::write(store.dir().join("b.txt"), "{}").unwrap();
        store.write(&json!({"ok": 1}), "tr-real");
        assert_eq!(store.list(10).len(), 1);
    }
}
